#!/usr/bin/env python3
"""
Regenerates the parts of the documentation that can be derived from the code,
so they never go stale:

  docs/CODE_MAP.md       every source file with its one-line purpose
  docs/API_ENDPOINTS.md  every server endpoint the app can call
  docs/STATUS_CODES.md   booking / trip / car status numbers and their meaning
  PROJECT_GUIDE.md       only the block between the AUTO markers

It also reports files that have no explanatory header yet, and files that are
not covered by START/END markers. Prose in PROJECT_GUIDE.md outside the AUTO
block is written by people and is never touched.

Usage:
    python tools/update_docs.py            # regenerate
    python tools/update_docs.py --check    # exit 1 when docs are out of date or
                                           # a file has no header (for CI / hooks)
    python tools/update_docs.py --quiet
"""
import datetime
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROJECT = os.path.abspath(os.path.join(HERE, '..'))
LIB = os.path.join(PROJECT, 'lib')
DOCS = os.path.join(PROJECT, 'docs')
GUIDE = os.path.join(PROJECT, 'PROJECT_GUIDE.md')
AUTO_START = '<!-- AUTO:inventory:start -->'
AUTO_END = '<!-- AUTO:inventory:end -->'


def read(path):
    with open(path, encoding='utf-8') as f:
        return f.read()


def header_of(src):
    """Return (what, notes) from the file's leading '// WHAT :' block."""
    what, notes, mode = [], [], None
    for line in src.split('\n')[:25]:
        t = line.strip()
        if t.startswith('// WHAT :'):
            mode = what
            what.append(t[len('// WHAT :'):].strip())
        elif t.startswith('// NOTES:'):
            mode = notes
            notes.append(t[len('// NOTES:'):].strip())
        elif t.startswith('//') and mode is not None and not t.startswith('// ===='):
            mode.append(t[2:].strip())
        elif mode is not None and not t.startswith('//'):
            break
    return ' '.join(what).strip(), ' '.join(notes).strip()


def collect_files():
    files = []
    for dp, dn, fn in os.walk(LIB):
        for f in sorted(fn):
            if f.endswith('.dart'):
                p = os.path.join(dp, f)
                files.append((os.path.relpath(p, LIB).replace('\\', '/'), p))
    files.sort()
    return files



def import_graph(files):
    """Return (reachable_from_main, case_mismatches). Imports are resolved
    ignoring letter case so the result is right on Windows too."""
    pkg = 'package:base_project_flutter/'
    known = {rel: p for rel, p in files}
    lower = {k.lower(): k for k in known}
    mismatches = set()

    def resolve(frm, imp):
        if imp.startswith(pkg):
            cand = imp[len(pkg):]
        elif imp.startswith(('package:', 'dart:')):
            return None
        else:
            cand = os.path.normpath(os.path.join(os.path.dirname(frm), imp)).replace(chr(92), '/')
        if cand in known:
            return cand
        if cand.lower() in lower:
            mismatches.add((frm, imp))
            return lower[cand.lower()]
        return None

    graph = {}
    for rel, p in files:
        imps = re.findall(r"(?m)^\s*import\s+'([^']+)'", read(p))
        graph[rel] = {r for r in (resolve(rel, i) for i in imps) if r}
    seen, stack = set(), ['main.dart']
    while stack:
        cur = stack.pop()
        if cur not in seen:
            seen.add(cur)
            stack.extend(graph.get(cur, ()))
    return seen, mismatches


def build_code_map(files, reachable=None):
    missing = []
    out = ['# Code map', '',
           '_Generated by `tools/update_docs.py` - do not edit by hand._', '',
           'Every source file under `lib/` and what it is for. ',
           'Files marked **INACTIVE** are fully commented out and can be deleted.', '']
    by_dir = {}
    for rel, p in files:
        d = rel.rsplit('/', 1)[0] if '/' in rel else '(root)'
        by_dir.setdefault(d, []).append((rel, p))
    for d in sorted(by_dir):
        out += [f'## `{d}`', '', '| File | What it does | Notes |', '|---|---|---|']
        for rel, p in by_dir[d]:
            src = read(p)
            what, notes = header_of(src)
            if not what:
                what = '**TODO: add a "// WHAT :" header**'
                missing.append(rel)
            name = rel.split('/')[-1]
            if reachable is not None and rel not in reachable:
                notes = ('**UNUSED: no screen imports it** ' + notes).strip()
            out.append(f'| `{name}` | {what} | {notes} |')
        out.append('')
    return '\n'.join(out) + '\n', missing


def build_api_doc():
    p = os.path.join(LIB, 'constants', 'apiConstants.dart')
    src = read(p)
    rows = []
    for m in re.finditer(r"(?m)^const\s+String\s+(\w+)\s*=\s*'([^']*)'", src):
        name, path = m.group(1), m.group(2)
        path = path.replace('?auth_code=', '')
        needs_login = '?auth_code=' in m.group(2)
        rows.append((name, path, 'yes' if needs_login else 'no'))
    out = ['# Server endpoints used by the app', '',
           '_Generated by `tools/update_docs.py` from `lib/constants/apiConstants.dart`._', '',
           'The server address itself is `apiBaseUrl` (set with '
           '`--dart-define=API_BASE_URL=...`; default is the live server).', '',
           '| Name in code | Path | Needs login |', '|---|---|---|']
    for name, path, login in rows:
        out.append(f'| `{name}` | `{path}` | {login} |')
    return '\n'.join(out) + '\n', len(rows)


def build_status_doc():
    p = os.path.join(LIB, 'constants', 'constants.dart')
    src = read(p)
    out = ['# Status numbers and types', '',
           '_Generated by `tools/update_docs.py` from `lib/constants/constants.dart`._', '',
           'These numbers are shared with the server and must stay identical.', '',
           '| Constant | Value | Meaning |', '|---|---|---|']
    for m in re.finditer(
            r"(?m)^const\s+(RIDER_TYPE_\w+|TRIP_TYPE_\w+|CAR_TYPE_\w+|STATUS_\w+|FIREBASE_STATUS_\w+|DRIVER|TAXI|AUTO|BIKE|OTHERS)\s*=\s*(\d+);\s*(?://\s*(.*))?",
            src):
        out.append(f'| `{m.group(1)}` | {m.group(2)} | {m.group(3) or ""} |')
    return '\n'.join(out) + '\n'


def build_auto_block(files, endpoints, missing, unmarked, unused=(), mismatches=()):
    now = datetime.date.today().isoformat()
    lines = [AUTO_START,
             f'_This block is generated by `tools/update_docs.py` (last run {now}). '
             'Do not edit it by hand._', '',
             f'- Source files: **{len(files)}**',
             f'- Server endpoints: **{endpoints}**  (see `docs/API_ENDPOINTS.md`)',
             '- Full file list: `docs/CODE_MAP.md`; status numbers: `docs/STATUS_CODES.md`',
             f'- Files without an explanatory header: **{len(missing)}**'
             + (' -> ' + ', '.join(f'`{m}`' for m in missing[:8]) if missing else ''),
             f'- Files without START/END markers: **{len(unmarked)}**'
             + (' (run `python tools/annotate_code.py`)' if unmarked else ''),
             f'- Files no screen imports (safe-to-delete candidates): **{len(unused)}**'
             ' - marked UNUSED in `docs/CODE_MAP.md`',
             f'- Imports whose letter case does not match the real file name: '
             f'**{len(mismatches)}** (works on Windows only; fix before building on Linux/macOS)',
             AUTO_END]
    return '\n'.join(lines)


def unmarked_files(files):
    out = []
    for rel, p in files:
        src = read(p)
        has_decl = re.search(r'(?m)^\s*(class|mixin|extension)\s+\w+', src)
        if has_decl and '// >>> START:' not in src:
            out.append(rel)
    return out


def write_if_changed(path, text):
    old = read(path) if os.path.exists(path) else None
    if old == text:
        return False
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    return True


def main():
    check = '--check' in sys.argv
    quiet = '--quiet' in sys.argv
    files = collect_files()
    reachable, mismatches = import_graph(files)
    unused = sorted(rel for rel, _ in files if rel not in reachable)
    code_map, missing = build_code_map(files, reachable)
    api_doc, n_endpoints = build_api_doc()
    status_doc = build_status_doc()
    unmarked = unmarked_files(files)

    changed = []
    # The date inside the guide block would make every run "different";
    # compare the generated documents without it.
    for path, text in (
        (os.path.join(DOCS, 'CODE_MAP.md'), code_map),
        (os.path.join(DOCS, 'API_ENDPOINTS.md'), api_doc),
        (os.path.join(DOCS, 'STATUS_CODES.md'), status_doc),
    ):
        old = read(path) if os.path.exists(path) else None
        if old != text:
            changed.append(os.path.relpath(path, PROJECT))
            if not check:
                write_if_changed(path, text)

    # PROJECT_GUIDE.md: replace only the AUTO block (create it if missing)
    guide = read(GUIDE) if os.path.exists(GUIDE) else ''
    block = build_auto_block(files, n_endpoints, missing, unmarked, unused, mismatches)
    if AUTO_START in guide and AUTO_END in guide:
        a = guide.index(AUTO_START)
        b = guide.index(AUTO_END) + len(AUTO_END)
        new_guide = guide[:a] + block + guide[b:]
    else:
        new_guide = guide.rstrip() + '\n\n## Live inventory (generated)\n\n' + block + '\n'
    # ignore the "last run" date when deciding if the guide changed
    strip_date = lambda t: re.sub(r'last run \d{4}-\d{2}-\d{2}', 'last run -', t)
    if strip_date(new_guide) != strip_date(guide):
        changed.append(os.path.relpath(GUIDE, PROJECT))
        if not check:
            write_if_changed(GUIDE, new_guide)

    if not quiet:
        print(f'files: {len(files)}  endpoints: {n_endpoints}')
        if missing:
            print('files WITHOUT a header:', *missing, sep='\n  ')
        if unmarked:
            print('files without START/END markers:', *unmarked, sep='\n  ')
        print('updated:' if not check else 'out of date:', *(changed or ['(nothing)']), sep='\n  ')
    if check and (changed or missing):
        sys.exit(1)


if __name__ == '__main__':
    main()
